use crate::span::Span;

#[derive(Clone, Debug, PartialEq)]
pub enum StrPart {
    Lit(String),
    /// `$name` inside a double-quoted string.
    Var(String, Span),
    /// `{$expr}` inside a double-quoted string: the source of the expression and
    /// the absolute byte offset where it starts.
    Expr(String, u32),
}

#[derive(Clone, Debug, PartialEq)]
pub enum Tok {
    Var(String),
    Ident(String),
    Int(i64),
    Float(f64),
    Str(String),
    Interp(Vec<StrPart>),
    /// `sql"..."`: interpolations become query parameters.
    Sql(Vec<StrPart>),
    InlineHtml(String),
    /// `<?=`
    EchoOpen,
    /// `?>`
    CloseTag,

    // Keywords.
    Function,
    Fn,
    Return,
    If,
    Elseif,
    Else,
    Endif,
    While,
    Endwhile,
    Do,
    For,
    Endfor,
    Foreach,
    Endforeach,
    As,
    Break,
    Continue,
    Echo,
    Class,
    Extends,
    New,
    Public,
    Private,
    Protected,
    Readonly,
    Static,
    True,
    False,
    Null,
    Match,
    Default,
    Try,
    Catch,
    Finally,
    Throw,
    Import,
    Export,
    Use,
    Is,
    Instanceof,
    Interface,
    Implements,
    Abstract,
    Enum,
    Case,
    Const,
    Final,

    // Punctuation.
    LParen,
    RParen,
    /// `#` before `[`: the start of an annotation, `#[Deprecated]`.
    Hash,
    LBracket,
    RBracket,
    LBrace,
    RBrace,
    Comma,
    Semi,
    Colon,
    DoubleColon,
    Arrow,
    NullsafeArrow,
    FatArrow,
    Question,
    QQ,
    QQEq,
    Dot,
    DotEq,
    DotDot,
    DotDotEq,
    Ellipsis,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    StarStar,
    PlusEq,
    MinusEq,
    StarEq,
    SlashEq,
    PercentEq,
    StarStarEq,
    PlusPlus,
    MinusMinus,
    Eq,
    EqEq,
    /// `===` — only lexed so the parser can explain that `==` is already strict.
    EqEqEq,
    NotEq,
    /// `!==`
    NotEqEq,
    Lt,
    Le,
    Gt,
    Ge,
    Spaceship,
    AndAnd,
    OrOr,
    Bang,
    Amp,
    Pipe,
    Caret,
    Tilde,
    Shl,
    Shr,

    Eof,
}

impl Tok {
    pub fn keyword(s: &str) -> Option<Tok> {
        Some(match s {
            "function" => Tok::Function,
            "fn" => Tok::Fn,
            "return" => Tok::Return,
            "if" => Tok::If,
            "elseif" => Tok::Elseif,
            "else" => Tok::Else,
            "endif" => Tok::Endif,
            "while" => Tok::While,
            "endwhile" => Tok::Endwhile,
            "do" => Tok::Do,
            "for" => Tok::For,
            "endfor" => Tok::Endfor,
            "foreach" => Tok::Foreach,
            "endforeach" => Tok::Endforeach,
            "as" => Tok::As,
            "break" => Tok::Break,
            "continue" => Tok::Continue,
            "echo" => Tok::Echo,
            "class" => Tok::Class,
            "extends" => Tok::Extends,
            "new" => Tok::New,
            "public" => Tok::Public,
            "private" => Tok::Private,
            "protected" => Tok::Protected,
            "readonly" => Tok::Readonly,
            "static" => Tok::Static,
            "true" => Tok::True,
            "false" => Tok::False,
            "null" => Tok::Null,
            "match" => Tok::Match,
            "default" => Tok::Default,
            "try" => Tok::Try,
            "catch" => Tok::Catch,
            "finally" => Tok::Finally,
            "throw" => Tok::Throw,
            "import" => Tok::Import,
            "export" => Tok::Export,
            "use" => Tok::Use,
            "is" => Tok::Is,
            "instanceof" => Tok::Instanceof,
            "interface" => Tok::Interface,
            "implements" => Tok::Implements,
            "abstract" => Tok::Abstract,
            "enum" => Tok::Enum,
            "case" => Tok::Case,
            "const" => Tok::Const,
            "final" => Tok::Final,
            _ => return None,
        })
    }

    /// Human-readable form used in "expected X, found Y" messages.
    pub fn describe(&self) -> String {
        match self {
            Tok::Var(n) => format!("variable `${n}`"),
            Tok::Ident(n) => format!("`{n}`"),
            Tok::Int(_) | Tok::Float(_) => "number".into(),
            Tok::Str(_) | Tok::Interp(_) => "string".into(),
            Tok::Sql(_) => "SQL literal".into(),
            Tok::InlineHtml(_) => "inline HTML".into(),
            Tok::EchoOpen => "`<?=`".into(),
            Tok::CloseTag => "`?>`".into(),
            Tok::Eof => "end of file".into(),
            other => format!("`{}`", other.text()),
        }
    }

    fn text(&self) -> &'static str {
        match self {
            Tok::Function => "function",
            Tok::Fn => "fn",
            Tok::Return => "return",
            Tok::If => "if",
            Tok::Elseif => "elseif",
            Tok::Else => "else",
            Tok::Endif => "endif",
            Tok::While => "while",
            Tok::Endwhile => "endwhile",
            Tok::Do => "do",
            Tok::For => "for",
            Tok::Endfor => "endfor",
            Tok::Foreach => "foreach",
            Tok::Endforeach => "endforeach",
            Tok::As => "as",
            Tok::Break => "break",
            Tok::Continue => "continue",
            Tok::Echo => "echo",
            Tok::Class => "class",
            Tok::Extends => "extends",
            Tok::New => "new",
            Tok::Public => "public",
            Tok::Private => "private",
            Tok::Protected => "protected",
            Tok::Readonly => "readonly",
            Tok::Static => "static",
            Tok::True => "true",
            Tok::False => "false",
            Tok::Null => "null",
            Tok::Match => "match",
            Tok::Default => "default",
            Tok::Try => "try",
            Tok::Catch => "catch",
            Tok::Finally => "finally",
            Tok::Throw => "throw",
            Tok::Import => "import",
            Tok::Export => "export",
            Tok::Use => "use",
            Tok::Is => "is",
            Tok::Instanceof => "instanceof",
            Tok::Interface => "interface",
            Tok::Implements => "implements",
            Tok::Abstract => "abstract",
            Tok::Enum => "enum",
            Tok::Case => "case",
            Tok::Const => "const",
            Tok::Final => "final",
            Tok::LParen => "(",
            Tok::RParen => ")",
            Tok::Hash => "#",
            Tok::LBracket => "[",
            Tok::RBracket => "]",
            Tok::LBrace => "{",
            Tok::RBrace => "}",
            Tok::Comma => ",",
            Tok::Semi => ";",
            Tok::Colon => ":",
            Tok::DoubleColon => "::",
            Tok::Arrow => "->",
            Tok::NullsafeArrow => "?->",
            Tok::FatArrow => "=>",
            Tok::Question => "?",
            Tok::QQ => "??",
            Tok::QQEq => "??=",
            Tok::Dot => ".",
            Tok::DotEq => ".=",
            Tok::DotDot => "..",
            Tok::DotDotEq => "..=",
            Tok::Ellipsis => "...",
            Tok::Plus => "+",
            Tok::Minus => "-",
            Tok::Star => "*",
            Tok::Slash => "/",
            Tok::Percent => "%",
            Tok::StarStar => "**",
            Tok::PlusEq => "+=",
            Tok::MinusEq => "-=",
            Tok::StarEq => "*=",
            Tok::SlashEq => "/=",
            Tok::PercentEq => "%=",
            Tok::StarStarEq => "**=",
            Tok::PlusPlus => "++",
            Tok::MinusMinus => "--",
            Tok::Eq => "=",
            Tok::EqEq => "==",
            Tok::EqEqEq => "===",
            Tok::NotEq => "!=",
            Tok::NotEqEq => "!==",
            Tok::Lt => "<",
            Tok::Le => "<=",
            Tok::Gt => ">",
            Tok::Ge => ">=",
            Tok::Spaceship => "<=>",
            Tok::AndAnd => "&&",
            Tok::OrOr => "||",
            Tok::Bang => "!",
            Tok::Amp => "&",
            Tok::Pipe => "|",
            Tok::Caret => "^",
            Tok::Tilde => "~",
            Tok::Shl => "<<",
            Tok::Shr => ">>",
            _ => "?",
        }
    }
}

#[derive(Clone, Debug)]
pub struct Token {
    pub tok: Tok,
    pub span: Span,
}
