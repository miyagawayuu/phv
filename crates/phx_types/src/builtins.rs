//! Signatures of built-in functions and methods. The implementations live in
//! `phx_std` under the same `imp` names; a test there checks that every
//! signature has an implementation.
//!
//! Signatures are written as PHX function types. For methods the receiver
//! is the first parameter. `T`, `U`, `K` and `V` are type parameters.

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Recv {
    Str,
    List,
    Map,
}

pub struct BuiltinSig {
    pub name: &'static str,
    pub recv: Option<Recv>,
    pub sig: &'static str,
    pub imp: &'static str,
    /// Only callable from the standard library modules.
    pub internal: bool,
}

const fn f(name: &'static str, sig: &'static str, imp: &'static str) -> BuiltinSig {
    BuiltinSig { name, recv: None, sig, imp, internal: false }
}

const fn m(recv: Recv, name: &'static str, sig: &'static str, imp: &'static str) -> BuiltinSig {
    BuiltinSig { name, recv: Some(recv), sig, imp, internal: false }
}

const fn internal(name: &'static str, sig: &'static str) -> BuiltinSig {
    BuiltinSig { name, recv: None, sig, imp: name, internal: true }
}

