/// Hints for PHP functions that do not exist in PHX.
pub fn php_hint(name: &str) -> Option<&'static str> {
    Some(match name {
        "eval" | "create_function" | "assert" => "dynamic code execution is not available in PHX",
        "extract" | "compact" | "parse_str" => "creating variables dynamically is not supported; use a map",
        "isset" => "use `??` (e.g. `$m[\"k\"] ?? \"default\"`) or `!= null`",
        "empty" => "compare explicitly, e.g. `$s->isEmpty()` or `$xs->isEmpty()`",
        "unset" => "build a new value instead",
        "var_dump" | "print_r" | "var_export" => "use `dump($value)`",
        "print" | "printf" | "sprintf" => "use `echo` with string interpolation: \"Hello {$name}\"",
        "strpos" | "stripos" => "use `$s->indexOf($needle)` (returns ?int)",
        "substr" | "mb_substr" => "use `$s->slice($start, $length)`",
        "in_array" => "use `$xs->contains($value)`",
        "array_map" => "use `$xs->map(fn($x) => ...)`",
        "array_filter" => "use `$xs->filter(fn($x) => ...)`",
        "array_keys" => "use `$m->keys()`",
        "array_values" => "use `$m->values()`",
        "array_key_exists" => "use `$m->has($key)`",
        "array_merge" => "use `$a->concat($b)` for lists or `$a->merge($b)` for maps",
        "array_reverse" => "use `$xs->reverse()`",
        "sort" | "rsort" | "usort" => "use `$xs->sorted()` or `$xs->sortBy(fn($a, $b) => $a <=> $b)`",
        "array_sum" => "use `$xs->sum()`",
        "array_slice" => "use `$xs->slice($start, $length)`",
        "intval" => "use `(int)$float` or `$string->toInt()`",
        "floatval" => "use `(float)$int` or `$string->toFloat()`",
        "strval" => "use `(string)$value`",
        "header" => "use `response()->header($name, $value)` from `std.http`",
        "is_null" => "use `$x == null`",
        "is_int" | "is_string" | "is_float" | "is_bool" | "is_array" => {
            "use `$x is int` (or string, float, bool, list, map)"
        }
        "mysqli_query" | "mysql_query" | "pg_query" => "use `std.db` with `sql\"...\"` queries",
        "md5" | "sha1" | "crypt" => "use `hash(\"sha256\", $s)`, or `password_hash()` for passwords",
        "rand" | "mt_rand" => "use `random_int($min, $max)` for anything security related",
        "session_start" | "session_regenerate_id" => "use `session()` from `std.http`",
        "setcookie" => "use `response()->cookie(...)` from `std.http`",
        "uniqid" => "use `random_token()`",
        _ => return None,
    })
}
