#!/usr/bin/env python3
"""Writes the Homebrew formula (phv.rb) and the Scoop manifest (phv.json) of a
release from its SHA256SUMS. Used by .github/workflows/package-managers.yml:

    python3 packaging/render.py 0.9.0 dist/SHA256SUMS out/

Homebrew gets the macOS archives and, on Linux, the static (musl) ones, which
need no particular C library; Scoop gets the Windows zip. Every archive must
be listed in SHA256SUMS, or nothing is written.
"""

import json
import re
import sys
from pathlib import Path

REPO = "miyagawayuu/phv"
DESCRIPTION = "Typed, PHP-like language for the web: run, serve, test and build"
HOMEPAGE = "https://phv-lang.org"

TARGETS = {
    "mac_arm": "aarch64-apple-darwin",
    "mac_intel": "x86_64-apple-darwin",
    "linux_arm": "aarch64-unknown-linux-musl",
    "linux_intel": "x86_64-unknown-linux-musl",
    "windows": "x86_64-pc-windows-msvc",
}


def archive(version: str, target: str) -> str:
    ext = "zip" if "windows" in target else "tar.gz"
    return f"phv-{version}-{target}.{ext}"


def url(version: str, name: str) -> str:
    return f"https://github.com/{REPO}/releases/download/v{version}/{name}"


def read_sums(path: Path) -> dict:
    sums = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.fullmatch(r"([0-9a-f]{64}) [ *]?(\S+)", line.strip())
        if m:
            sums[m.group(2)] = m.group(1)
    return sums


def formula(version: str, sums: dict) -> str:
    def entry(key: str) -> str:
        name = archive(version, TARGETS[key])
        return f'      url "{url(version, name)}"\n      sha256 "{sums[name]}"'

    return f'''# Generated by packaging/render.py from the release's SHA256SUMS; do not edit.
class Phv < Formula
  desc "{DESCRIPTION}"
  homepage "{HOMEPAGE}"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
{entry("mac_arm")}
    end
    on_intel do
{entry("mac_intel")}
    end
  end

  on_linux do
    on_arm do
{entry("linux_arm")}
    end
    on_intel do
{entry("linux_intel")}
    end
  end

  def install
    bin.install "phv"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/phv --version")
    (testpath/"hello.phv").write "<?phv\\necho 1 + 2;\\n"
    assert_equal "3", shell_output("#{{bin}}/phv run #{{testpath}}/hello.phv")
  end
end
'''


def manifest(version: str, sums: dict) -> str:
    target = TARGETS["windows"]
    name = archive(version, target)
    doc = {
        "version": version,
        "description": DESCRIPTION,
        "homepage": HOMEPAGE,
        "license": "MIT",
        "architecture": {
            "64bit": {
                "url": url(version, name),
                "hash": sums[name],
                "extract_dir": f"phv-{version}-{target}",
            }
        },
        "bin": "phv.exe",
        "checkver": "github",
        "autoupdate": {
            "architecture": {
                "64bit": {
                    "url": f"https://github.com/{REPO}/releases/download/v$version/phv-$version-{target}.zip",
                    "extract_dir": f"phv-$version-{target}",
                }
            },
            "hash": {"url": "$baseurl/SHA256SUMS"},
        },
    }
    return json.dumps(doc, indent=4) + "\n"


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    version, sums_path, out = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        print(f"error: not a version: {version}", file=sys.stderr)
        return 1
    sums = read_sums(sums_path)
    missing = [archive(version, t) for t in TARGETS.values() if archive(version, t) not in sums]
    if missing:
        print("error: SHA256SUMS does not list " + ", ".join(missing), file=sys.stderr)
        return 1
    out.mkdir(parents=True, exist_ok=True)
    (out / "phv.rb").write_text(formula(version, sums), encoding="utf-8", newline="\n")
    (out / "phv.json").write_text(manifest(version, sums), encoding="utf-8", newline="\n")
    print(f"wrote {out / 'phv.rb'} and {out / 'phv.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
